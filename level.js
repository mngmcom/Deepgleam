// Deepgleam – Leveldaten
//
// Jedes Level besteht aus Abschnitten (Chunks), die von links nach rechts
// aneinandergehängt werden. Jeder Abschnitt hat 12 Zeilen, eine Kachel = 16 px.
// Zeile 9 ist die normale Laufebene, Zeilen 10–11 sind Boden.
//
// Legende:
//   #  Fels (fest)              B  Steinziegel (fest)
//   =  Holzplanke (von unten durchspringbar, mit Pfeil runter durchfallen)
//   %  Bröckelplatte (wie Planke, zerfällt kurz nach dem Betreten)
//   ^  Stacheln                 ~  Lava (tödlich)
//   |  Holzbalken (Deko)        .  Luft
//   P  Startpunkt Spieler       C  Checkpoint (Laterne)
//   E  Ausgang (nächstes Level) T  Schatztruhe (Spielziel)
//   o  Goldnugget (50)          *  Edelstein (250)
//   f  Wandfackel (Licht)       x  Leuchtkristall (Deko)   m  Leuchtpilz (Deko)
//   v  Stalaktit (fällt herab)
//   S  Schild – einige Sekunden unverwundbar, Monster werden bei Berührung besiegt
//   D  Doppelgold – Goldnuggets zählen einige Sekunden lang doppelt
//
// Monster:
//   s  Spinne (läuft)           b  Fledermaus (fliegt)
//   K  Kristallkäfer – nur besiegbar, wenn die Kristalle eingefahren sind
//   G  Sporenpilz – schießt Sporen auf den Spieler
//   L  Glutling – springt aus der Lava, nicht besiegbar (in Lava setzen)
//
// Themen (theme): earth, crystal, fungus, lava
// Sprungweite: ca. 3 Kacheln hoch, ca. 3-4 Kacheln weit.
//
// Tiefer gehen: down(2, [ ... ]) setzt diesen Abschnitt und alle folgenden
// 2 Zeilen tiefer. So führt jedes Level stufenweise weiter in die Höhle hinab.
// Der linke Rand des tieferen Abschnitts sollte in den Zeilen 6 und 7 frei sein,
// damit man vom vorherigen Abschnitt hinunterlaufen kann.

